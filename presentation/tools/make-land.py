"""Builds js/data/land.js: land points for the presentation globe.

Samples the site's own stippled world map (public/art/world-dots.png, equirectangular,
bounds lon -125..155, lat -45..75 as in src/lib/geo-cities.ts) on a Fibonacci sphere.
"""
import math, pathlib, json
import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
im = np.array(Image.open(ROOT / "public/art/world-dots.png"))[:, :, 3].astype(np.float32)
H, W = im.shape
# blur-ish occupancy: max over a small window so stipple gaps don't read as sea
from PIL import ImageFilter
occ = np.array(Image.fromarray(im.astype(np.uint8)).filter(ImageFilter.MaxFilter(9)).filter(ImageFilter.GaussianBlur(4)))
LON0, LON1, LAT0, LAT1 = -125, 155, -45, 75
N = 26000
pts = []
golden = math.pi * (3 - math.sqrt(5))
for i in range(N):
    y = 1 - 2 * (i + 0.5) / N
    lat = math.degrees(math.asin(y))
    lon = math.degrees((i * golden) % (2 * math.pi)) - 180
    if not (LAT0 <= lat <= LAT1 and LON0 <= lon <= LON1):
        continue
    px = int((lon - LON0) / (LON1 - LON0) * (W - 1))
    py = int((LAT1 - lat) / (LAT1 - LAT0) * (H - 1))
    if occ[py, px] > 60:
        pts.append([round(lat, 2), round(lon, 2)])
out = ROOT / "presentation/js/data/land.js"
flat = [v for p in pts for v in p]
out.write_text("/* Generated by tools/make-land.py from public/art/world-dots.png. Pairs of [lat, lon]. */\nwindow.LAND = " + json.dumps(flat, separators=(",", ":")) + ";\n")
print(len(pts), "land points,", out.stat().st_size // 1024, "KB")
